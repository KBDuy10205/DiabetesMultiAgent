from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Iterable

from .common import ROOT, read_jsonl, sha256_text, write_json

SCHEMA = """CREATE CONSTRAINT source_id_unique IF NOT EXISTS FOR (n:Source) REQUIRE n.id IS UNIQUE;
CREATE CONSTRAINT chunk_id_unique IF NOT EXISTS FOR (n:Chunk) REQUIRE n.id IS UNIQUE;
CREATE CONSTRAINT disease_id_unique IF NOT EXISTS FOR (n:Disease) REQUIRE n.id IS UNIQUE;
CREATE CONSTRAINT concept_id_unique IF NOT EXISTS FOR (n:Concept) REQUIRE n.id IS UNIQUE;
CREATE CONSTRAINT assertion_id_unique IF NOT EXISTS FOR (n:Assertion) REQUIRE n.id IS UNIQUE;
CREATE INDEX chunk_source_id IF NOT EXISTS FOR (n:Chunk) ON (n.source_id);
"""


def _literal(value: Any) -> str:
    """Serialize data values as Cypher literals, not JSON maps.

    Cypher accepts JSON-like lists and strings, but map keys must be Cypher
    identifiers (`{id: "..."}`), not JSON keys (`{"id": "..."}`).  Property
    names passed here are a code-owned allowlist.
    """
    if value is None:
        return "null"
    if value is True:
        return "true"
    if value is False:
        return "false"
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, list):
        return "[" + ", ".join(_literal(item) for item in value) + "]"
    if isinstance(value, dict):
        return "{" + ", ".join(f"{key}: {_literal(item)}" for key, item in value.items()) + "}"
    raise TypeError(f"Unsupported Cypher literal type: {type(value).__name__}")


def _batches(records: list[dict[str, Any]], size: int = 100) -> Iterable[list[dict[str, Any]]]:
    for index in range(0, len(records), size):
        yield records[index:index + size]


def _node_batches(label: str, records: list[dict[str, Any]], properties: list[str]) -> str:
    statements: list[str] = []
    for batch in _batches(sorted(records, key=lambda item: item["id"])):
        rows = [{field: item.get(field) for field in properties if item.get(field) is not None} for item in batch]
        sets = ", ".join(f"n.{field} = row.{field}" for field in properties if field != "id")
        statements.append(f"UNWIND {_literal(rows)} AS row\nMERGE (n:{label} {{id: row.id}})\nSET {sets};\n")
    return "".join(statements)


def _relationships(sources: list[dict[str, Any]], chunks: list[dict[str, Any]], mentions: list[dict[str, Any]], assertions: list[dict[str, Any]]) -> str:
    lines: list[str] = []
    for chunk in sorted(chunks, key=lambda item: item["id"]):
        lines.append(f"MATCH (ch:Chunk {{id: {_literal(chunk['id'])}}}), (s:Source {{id: {_literal(chunk['source_id'])}}}) MERGE (ch)-[:FROM_SOURCE]->(s);\n")
    for mention in sorted(mentions, key=lambda item: (item["chunk_id"], item["entity_id"], item["start"])):
        label = "Disease" if mention["entity_id"].startswith("disease_") else "Concept"
        props = _literal({"start": mention["start"], "end": mention["end"], "matched_text": mention["matched_text"]})
        lines.append(f"MATCH (ch:Chunk {{id: {_literal(mention['chunk_id'])}}}), (e:{label} {{id: {_literal(mention['entity_id'])}}}) MERGE (ch)-[r:MENTIONS {{start: {mention['start']}, end: {mention['end']}}}]->(e) SET r.matched_text = {_literal(mention['matched_text'])};\n")
    for assertion in sorted(assertions, key=lambda item: item["id"]):
        lines.append(f"MATCH (d:Disease {{id: {_literal(assertion['disease_id'])}}}), (a:Assertion {{id: {_literal(assertion['id'])}}}) MERGE (d)-[:HAS_ASSERTION]->(a);\n")
        for concept_id in assertion.get("concept_ids", []): lines.append(f"MATCH (a:Assertion {{id: {_literal(assertion['id'])}}}), (c:Concept {{id: {_literal(concept_id)}}}) MERGE (a)-[:ABOUT]->(c);\n")
        for chunk_id in assertion.get("evidence_chunk_ids", []): lines.append(f"MATCH (a:Assertion {{id: {_literal(assertion['id'])}}}), (ch:Chunk {{id: {_literal(chunk_id)}}}) MERGE (a)-[:SUPPORTED_BY]->(ch);\n")
    return "".join(lines)


def run() -> dict[str, Any]:
    sources, chunks = read_jsonl("data/kb/sources.jsonl"), read_jsonl("data/kb/chunks.jsonl")
    entities, mentions, assertions = read_jsonl("data/kg/entities.jsonl"), read_jsonl("data/kg/mentions.jsonl"), read_jsonl("data/kg/assertions_approved.jsonl")
    diseases = [item for item in entities if item["label"] == "Disease"]
    concepts = [item for item in entities if item["label"] == "Concept"]
    data = "// Generated by kb_pipeline; source data are local, evidence-first records.\n" + _node_batches("Source", sources, ["id", "title", "url", "source_path", "raw_sha256", "published_at", "accessed_at", "format", "quality_status", "demo"]) + _node_batches("Chunk", chunks, ["id", "source_id", "text", "text_sha256", "start", "end", "quality_status", "demo"]) + _node_batches("Disease", diseases, ["id", "name", "aliases"]) + _node_batches("Concept", concepts, ["id", "name", "kind", "aliases"]) + _node_batches("Assertion", assertions, ["id", "text", "review_status", "evidence_quote", "demo"]) + _relationships(sources, chunks, mentions, assertions)
    verify = """MATCH (n) RETURN labels(n) AS labels, count(*) AS count ORDER BY labels;
MATCH ()-[r]->() RETURN type(r) AS relationship_type, count(*) AS count ORDER BY relationship_type;
MATCH (ch:Chunk) WHERE NOT EXISTS { MATCH (ch)-[:FROM_SOURCE]->(:Source) } RETURN ch.id AS chunk_without_source;
MATCH (a:Assertion) WHERE NOT EXISTS { MATCH (a)-[r]->(:Chunk)-[:FROM_SOURCE]->(:Source) WHERE type(r) = 'SUPPORTED_BY' } RETURN a.id AS assertion_without_evidence;
"""
    out = ROOT / "output/cypher"; out.mkdir(parents=True, exist_ok=True)
    (out / "schema.cypher").write_text(SCHEMA, encoding="utf-8", newline="\n")
    (out / "data.cypher").write_text(data, encoding="utf-8", newline="\n")
    (out / "knowledge.cypher").write_text(SCHEMA + "\n" + data, encoding="utf-8", newline="\n")
    (out / "verify.cypher").write_text(verify, encoding="utf-8", newline="\n")
    manifest = {"sources": len(sources), "chunks": len(chunks), "entities": len(entities), "mentions": len(mentions), "approved_assertions": len(assertions), "knowledge_cypher_sha256": sha256_text(SCHEMA + "\n" + data)}
    write_json("reports/build_manifest.json", manifest)
    return manifest
